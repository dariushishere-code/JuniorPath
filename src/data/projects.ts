export const getProjectsByStack = (stack: Stack): Project[] => {
  return projects
    .filter((p) => p.stack === stack)
    .sort((a, b) => a.order - b.order);
};

export const getProjectById = (id: string): Project | undefined => {
  return projects.find((p) => p.id === id);
};

export const isProjectUnlocked = (
  projectId: string,
  stack: Stack,
  completedProjects: string[],
): boolean => {
  const stackProjects = getProjectsByStack(stack);
  const index = stackProjects.findIndex((p) => p.id === projectId);
  if (index === -1) return false;
  if (index === 0) return true;
  // A project is unlocked when the previous project in the same stack is completed
  return completedProjects.includes(stackProjects[index - 1].id);
};